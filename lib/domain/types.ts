/**
 * Shared domain types. These are provider-agnostic: every railway data
 * provider maps its own response format into these shapes, and the UI and
 * journey planner only ever see these.
 *
 * Time conventions
 * - Absolute instants are epoch milliseconds (`number`).
 * - Timetable times are minute offsets from 00:00 IST on the day the train
 *   leaves its origin (so 25:30 on day 2 of the journey is 1530).
 * - Calendar dates are `YYYY-MM-DD` strings in IST.
 */

/** How trustworthy a value is. Shown to users next to every time / platform. */
export type DataQuality =
  /** Reported by a live running-status feed and still fresh. */
  | "live"
  /** Derived from live data (e.g. a delay propagated to later stops) or live data that has gone stale. */
  | "estimated"
  /** Straight from the published timetable, no live information. */
  | "scheduled"
  /** Generated by the development sample provider. Never real. */
  | "simulated"
  /** No data at all. */
  | "unavailable";

export interface Coordinates {
  lat: number;
  lng: number;
}

export interface StationSummary {
  code: string;
  name: string;
  city?: string | null;
}

export interface Station extends StationSummary {
  coordinates?: Coordinates | null;
  zone?: string | null;
}

export interface TrainSummary {
  number: string;
  name: string;
  sourceCode?: string | null;
  destinationCode?: string | null;
}

export type Weekday = "sun" | "mon" | "tue" | "wed" | "thu" | "fri" | "sat";
export const WEEKDAYS: Weekday[] = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];

export interface ScheduleStop {
  sequence: number;
  stationCode: string;
  stationName: string;
  /** Minutes from origin-day midnight IST. `null` at the origin. */
  arrival: number | null;
  /** Minutes from origin-day midnight IST. `null` at the destination. */
  departure: number | null;
  /** Whether the train halts here (false = passes through). */
  isHalt: boolean;
  distanceKm?: number | null;
  /** Usual / booked platform from the timetable. Not a live assignment. */
  scheduledPlatform?: string | null;
  coordinates?: Coordinates | null;
}

export interface TrainSchedule {
  number: string;
  name: string;
  type?: string | null;
  sourceCode: string;
  destinationCode: string;
  /** Weekdays on which the train leaves its origin. */
  runDays: Weekday[];
  stops: ScheduleStop[];
}

export type LiveStopStatus = "departed" | "arrived" | "upcoming" | "skipped" | "unknown";

export interface LiveStop {
  stationCode: string;
  /** Actual or expected instants (epoch ms). */
  expectedArrival: number | null;
  expectedDeparture: number | null;
  actualArrival: number | null;
  actualDeparture: number | null;
  delayArrivalMinutes: number | null;
  delayDepartureMinutes: number | null;
  status: LiveStopStatus;
  /** Platform reported by the live feed for this run. */
  livePlatform?: string | null;
}

export type RunningState =
  | "not_started"
  | "running"
  | "at_station"
  | "completed"
  | "cancelled"
  | "unknown";

export interface TrainPosition extends Coordinates {
  /** True only when the provider says the position is a real reported fix, not an interpolation. */
  isActual: boolean;
}

export interface LiveTrainStatus {
  trainNumber: string;
  /** Date the train left (or will leave) its origin. */
  journeyDate: string;
  /** "live" from a real feed, "simulated" from the sample provider. */
  source: "live" | "simulated";
  /** When the provider last received a position/status update. */
  lastUpdatedAt: number;
  runningState: RunningState;
  /** Station the train is at or most recently passed. */
  currentStationCode: string | null;
  /** 0..1 progress from current station towards the next one, if known. */
  segmentProgress?: number | null;
  delayMinutes: number | null;
  stops: LiveStop[];
  position?: TrainPosition | null;
  /** Speed reported (or, for simulated data, derived) at the last update. */
  speedKmh?: number | null;
  /** Diversions, cancellations, reschedules reported by the provider. */
  notices: string[];
}

/** A train halting at (or passing) a station, from the station timetable. */
export interface StationScheduleEntry {
  trainNumber: string;
  trainName: string;
  sourceCode: string;
  destinationCode: string;
  runDays: Weekday[];
  /** Minutes from origin-day midnight IST. */
  arrival: number | null;
  departure: number | null;
  isHalt: boolean;
  scheduledPlatform?: string | null;
}

export type LiveBoardState = "at_station" | "upcoming" | "departed" | "scheduled";

/** One row from a provider's live arrivals/departures board. */
export interface LiveBoardEntry {
  trainNumber: string;
  trainName?: string | null;
  journeyDate?: string | null;
  state: LiveBoardState;
  expectedArrival: number | null;
  expectedDeparture: number | null;
  delayMinutes: number | null;
  livePlatform?: string | null;
}

export interface StationLiveBoard {
  stationCode: string;
  source: "live" | "simulated";
  fetchedAt: number;
  entries: LiveBoardEntry[];
}

/**
 * Track layout for a station. Only used to say "arrives from the left/right"
 * when real layout data exists. Without it, the UI shows direction by
 * previous/next station only.
 */
export interface StationLayout {
  stationCode: string;
  /** Adjacent station codes reached by leaving on the left side of the diagram. */
  leftNeighbours: string[];
  /** Adjacent station codes reached by leaving on the right side of the diagram. */
  rightNeighbours: string[];
  platforms: string[];
  /** Where this layout came from (shown in the UI). */
  sourceNote: string;
}

/** A train that runs from one station to another (both halts, in that order). */
export interface TrainBetween {
  trainNumber: string;
  trainName: string;
  type?: string | null;
  /** Weekdays the train leaves its ORIGIN. */
  runDays: Weekday[];
  fromCode: string;
  fromName: string;
  toCode: string;
  toName: string;
  /** Minutes from origin-day midnight IST at the from/to stations. */
  departure: number;
  arrival: number;
  distanceKm?: number | null;
  haltsBetween?: number | null;
}

export interface Coach {
  /** 1 = first vehicle as listed by the source (usually the engine end). */
  position: number;
  code: string;
  classType?: string | null;
  name?: string | null;
}

/** Order of coaches for a train at a station. */
export interface CoachPosition {
  trainNumber: string;
  stationCode: string;
  platform: string | null;
  coaches: Coach[];
  source: "provider" | "simulated";
}

export interface ProviderCapabilities {
  liveStatus: boolean;
  liveStationBoard: boolean;
  livePlatforms: boolean;
  trainPositions: boolean;
  stationLayouts: boolean;
  nearbyStations: boolean;
  trainsBetween: boolean;
  coachPositions: boolean;
}

export interface ProviderInfo {
  id: string;
  name: string;
  /** True for any provider whose data is not real. The UI shows a banner. */
  isSample: boolean;
  capabilities: ProviderCapabilities;
  notes: string[];
}
